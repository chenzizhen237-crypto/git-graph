/**
 * Turns the variables of the Nib design file into code, so the design stays
 * the source of truth:
 *
 * - src/styles/tokens.css: every colour and number as a CSS custom property,
 *   Light on :root, Dark under [data-theme="dark"] (or the system setting),
 *   and the Stage axis under [data-stage="…"], plus a Tailwind `@theme`
 *   that maps them to utilities: `bg-sidebar`, `text-muted`, `border-subtle`,
 *   `text-ref-head`, `rounded-md`, `text-sm`, `h-titlebar`…
 * - src/lib/tokens.ts: the Stage strings and flags (labels, banner copy…).
 *
 * Run with `pnpm tokens` after `./assets/sync-design.sh`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

type Value = string | number | boolean
type Themed = { value: Value; theme?: Record<string, string> }
type Variable = { type: 'color' | 'number' | 'string' | 'boolean'; value: Value | Themed[]; collection?: string; description?: string }

const root = fileURLToPath(new URL('..', import.meta.url))
const doc = JSON.parse(readFileSync(`${root}assets/design/Git Graph Desktop.nib`, 'utf8')) as {
  variables: Record<string, Variable>
  themes: Record<string, string[]>
}

// Raw names that Tailwind's theme namespaces would shadow (`--text-xs`,
// `--radius-md`, `--font-sans`) get a prefix of their own.
const SIZE_GROUPS: Record<string, string> = { text: 'fs', radius: 'rad', font: 'ff' }
const cssName = (name: string) => {
  const [group = '', rest] = name.split('/')
  const prefix = SIZE_GROUPS[group]
  const isSize = prefix && (group !== 'text' || /^(xs|sm|md|lg|x+l|\d?xl)$/.test(rest ?? ''))
  return `--${(isSize ? `${prefix}/${rest}` : name).replace(/\//g, '-')}`
}
const FONTS: Record<string, string> = {
  Inter: `'Inter Variable', Inter, -apple-system, system-ui, sans-serif`,
  'JetBrains Mono': `'JetBrains Mono Variable', 'JetBrains Mono', ui-monospace, Menlo, monospace`,
}

/** A value as CSS: aliases become var(), numbers become px. */
function css(v: Value, type: Variable['type']): string {
  if (typeof v === 'string' && v.startsWith('$')) return `var(${cssName(v.slice(1))})`
  if (type === 'number') return `${v}px`
  if (type === 'string') return FONTS[v as string] ?? JSON.stringify(v)
  return String(v)
}

const variants = (v: Variable): Themed[] => (Array.isArray(v.value) ? v.value : [{ value: v.value }])

const base: string[] = []
const dark: string[] = []
const stages: Record<string, string[]> = {}
const stageData: Record<string, Record<string, Value>> = {}

for (const [name, v] of Object.entries(doc.variables)) {
  const isStage = v.collection === 'Stage'
  if (isStage && (v.type === 'string' || v.type === 'boolean')) {
    const key = name.replace(/^stage\//, '').replace(/-(\w)/g, (_, c: string) => c.toUpperCase())
    for (const t of variants(v)) {
      const stage = t.theme?.Stage ?? 'Clean'
      ;(stageData[stage] ??= {})[key] = t.value
    }
    continue
  }
  // Font names: a string variable aliasing another resolves through var().
  if (v.type === 'string' && !['sans', 'mono', 'font/sans', 'font/mono'].includes(name)) continue
  if (v.type === 'boolean') continue
  for (const t of variants(v)) {
    const line = `  ${cssName(name)}: ${css(t.value, v.type)};`
    if (t.theme?.Mode === 'Dark') dark.push(line)
    else if (t.theme?.Stage) (stages[t.theme.Stage] ??= []).push(line)
    else base.push(line)
  }
}

/**
 * Tailwind utility names. Semantic groups drop their prefix where the utility
 * already says it (`bg/app` → `bg-app`, `text/muted` → `text-muted`,
 * `border/subtle` → `border-subtle`); the rest keep their path (`ref-head`).
 */
function utilityName(name: string, v: Variable): string | null {
  const [group = '', rest = ''] = name.split('/')
  if (!name.includes('/')) return v.description?.startsWith('Legacy') || v.type !== 'color' ? null : name
  if (['bg', 'border'].includes(group)) return rest
  if (group === 'text') return rest
  if (group === 'macos' || group === 'avatar') return name.replace('/', '-')
  return name.replace(/\//g, '-')
}

const theme: string[] = ['  --color-*: initial;', '  --color-white: #fff;', '  --color-black: #000;', '  --color-transparent: transparent;', '  --color-current: currentColor;']
for (const [name, v] of Object.entries(doc.variables)) {
  const css = `var(${cssName(name)})`
  if (v.type === 'color') {
    const u = utilityName(name, v)
    if (u) theme.push(`  --color-${u}: ${css};`)
  } else if (v.type === 'number') {
    const [group, rest] = name.split('/')
    if (group === 'text') theme.push(`  --text-${rest}: ${css};`)
    else if (group === 'radius') theme.push(`  --radius-${rest}: ${css};`)
    else if (group === 'size') theme.push(`  --spacing-${rest}: ${css};`)
  }
}
theme.push('  --font-sans: var(--ff-sans);', '  --font-mono: var(--ff-mono);')

const header = '/* Generated by scripts/tokens.ts from assets/design/Git Graph Desktop.nib. Do not edit. */\n\n'
const out =
  header +
  `@theme inline {\n${theme.join('\n')}\n}\n\n` +
  `:root {\n${base.join('\n')}\n}\n\n` +
  `:root[data-theme='dark'] {\n${dark.join('\n')}\n  color-scheme: dark;\n}\n\n` +
  `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${dark.map(l => '  ' + l).join('\n')}\n    color-scheme: dark;\n  }\n}\n\n` +
  Object.entries(stages)
    .map(([s, lines]) => `[data-stage='${s}'] {\n${lines.join('\n')}\n}`)
    .join('\n\n') +
  '\n'
writeFileSync(`${root}src/styles/tokens.css`, out)

const stageNames = doc.themes.Stage ?? Object.keys(stageData)
const ts =
  '// Generated by scripts/tokens.ts from assets/design/Git Graph Desktop.nib. Do not edit.\n\n' +
  `export const STAGES = ${JSON.stringify(stageNames)} as const\n\n` +
  `export type Stage = (typeof STAGES)[number]\n\n` +
  `export const STAGE_COPY = ${JSON.stringify(stageData, null, 2)} as const satisfies Record<Stage, unknown>\n`
writeFileSync(`${root}src/lib/tokens.ts`, ts)

console.log(`tokens: ${base.length + dark.length} css lines, ${stageNames.length} stages`)
